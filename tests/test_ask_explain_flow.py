def test_ask_tab_local_model_explanation_failure_fallback(ask_test_env) -> None:
    """Requirement C.4: Explanation failure provides deterministic fallback and preserves results."""
    cfg = ask_test_env["cfg"]
    user = ask_test_env["user"]
    ingest = ask_test_env["ingest"]
    log = AuditLog(ask_test_env["db_path"])

    state = MockSessionState({
        "ingest": ingest,
        "last_result": None,
        "last_explanation": None,
    })

    with patch("private_analyst.ui.streamlit_app.st") as mock_st, \
         patch("private_analyst.ui.streamlit_app.explain_results", side_effect=RuntimeError("Ollama crashed")), \
         patch("private_analyst.ui.streamlit_app._get_audit_log", return_value=log):
        mock_st.session_state = state
        mock_st.text_input.return_value = "Summarize the dataset."
        mock_st.button.side_effect = lambda label, *args, **kwargs: label == "Run analysis"

        _ask_tab(cfg, user)

        # Deterministic result MUST be saved
        assert state.last_result is not None
        assert state.last_result.intent == "summarize"

        # Explanation MUST fall back deterministically
        assert state.last_explanation is not None
        assert state.last_explanation["source"] == "deterministic_fallback"
        assert state.last_explanation["model_available"] is False
        assert "AI model error: RuntimeError" in state.last_explanation["model_detail"]
        assert len(state.last_explanation["text"]) > 0

        # UI renders fallback information
        mock_st.info.assert_any_call("Local AI model is offline. Displaying deterministic structured engine findings below.")
        mock_st.markdown.assert_any_call(state.last_explanation["text"])


