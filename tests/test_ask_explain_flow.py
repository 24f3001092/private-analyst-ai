def test_ask_tab_successful_analysis_and_visible_result_state(ask_test_env) -> None:
    """Requirement C.1: Successful analysis populates session_state and renders results visibly."""
    cfg = ask_test_env["cfg"]
    user = ask_test_env["user"]
    ingest = ask_test_env["ingest"]
    log = AuditLog(ask_test_env["db_path"])

    state = MockSessionState({
        "ingest": ingest,
        "last_result": None,
        "last_explanation": None,
    })

    fake_explanation = {
        "source": "local_model",
        "model_available": True,
        "model_detail": "Online (mock_model)",
        "text": "Executive Summary: The sales dataset contains 3 products with total revenue of 450.",
        "engine_facts": "Facts: 3 products, revenue 450",
    }

    with patch("private_analyst.ui.streamlit_app.st") as mock_st, \
         patch("private_analyst.ui.streamlit_app.explain_results", return_value=fake_explanation), \
         patch("private_analyst.ui.streamlit_app._get_audit_log", return_value=log):
        mock_st.session_state = state
        mock_st.text_input.return_value = "Summarize the dataset."
        mock_st.button.side_effect = lambda label, *args, **kwargs: label == "Run analysis"

        _ask_tab(cfg, user)

        # Session state must be populated
        assert state.last_result is not None
        assert isinstance(state.last_result, OperationResult)
        assert state.last_result.intent == "summarize"
        assert state.last_result.status == "ok"
        assert state.last_explanation == fake_explanation

        # Results must be rendered
        mock_st.write.assert_any_call("### Verified Analytical Facts & Metrics")
        mock_st.write.assert_any_call("### AI Analysis & Narrative")
        mock_st.success.assert_any_call(
            "Narrative generated by local model (Online (mock_model)). Verified totals remain engine-computed."
        )
        mock_st.markdown.assert_any_call(fake_explanation["text"])

        # Audit event recorded
        events = log.list_for_org(user.org_id)
        assert any(e["action"] == "run_analysis" and "Operation: summarize" in e["detail"] for e in events)


